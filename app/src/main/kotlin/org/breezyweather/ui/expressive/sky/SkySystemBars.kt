package org.breezyweather.ui.expressive.sky

import android.app.Activity
import androidx.compose.runtime.Composable
import androidx.compose.runtime.SideEffect
import androidx.compose.ui.graphics.luminance
import androidx.compose.ui.platform.LocalView
import androidx.core.view.WindowCompat

/**
 * Makes the status bar and navigation bar icons (clock, notification icons, battery, gesture bar)
 * match the sky's text: dark icons on light skies, light icons on dark skies, so icons and text
 * always share one colour family. Call it on any screen whose background is a sky.
 */
@Composable
fun SkySystemBars(palette: SkyPalette) {
    val view = LocalView.current
    if (view.isInEditMode) return
    val darkIcons = palette.text.luminance() < 0.5f
    SideEffect {
        val window = (view.context as? Activity)?.window ?: return@SideEffect
        WindowCompat.getInsetsController(window, view).apply {
            isAppearanceLightStatusBars = darkIcons
            isAppearanceLightNavigationBars = darkIcons
        }
    }
}
